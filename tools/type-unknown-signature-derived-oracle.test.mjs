import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {test} from 'node:test';
import {compilerHookOracle} from './type-oracle.mjs';
import {lineStarts,position} from './semantic-oracle.mjs';
const root=fileURLToPath(new URL('../fixtures/types/native-unknown-signature/',import.meta.url));
for (const config of ['derived','derived-loose','derived-exact']) test(`native composed unknown signature return replay (${config})`,async t=>{
 const source=fs.readFileSync(path.join(root,'derived.ts'),'utf8');
 const offset=name=>source.indexOf(`/*#${name}*/`)+name.length+5;
 const at=name=>({file:'derived.ts',...position(lineStarts(source),offset(name))});
 const loc=(name,length)=>({file:'derived.ts',start:position(lineStarts(source),offset(name)),end:position(lineStarts(source),offset(name)+length)});
 const member=await compilerHookOracle(path.join(root,config+'.json'),{operation:'member',at:at('seed')});
 const returned=await compilerHookOracle(path.join(root,config+'.json'),{at:at('returned')});
 const selected=await compilerHookOracle(path.join(root,config+'.json'),{at:at('selected'),inspectUnknownSignatureReturns:true});
 fs.mkdirSync('.cc/temp',{recursive:true});
 fs.writeFileSync(`.cc/temp/native-unknown-signature-${config}.json`,JSON.stringify({member,returned,selected},null,2));
 assert.deepEqual(member.schedule,{checker:'one',relationshipBeforeCandidates:true,searchSetCount:1,candidates:4});
 const origin={kind:'PropertySignature',location:loc('seed',5)};
 assert.deepEqual(member.groups,[{origins:[origin],occurrences:[loc('seed',5),loc('warm',5)]}]);
 assert.deepEqual(member.candidateObservations.map(row=>({location:row.location,origins:row.origins})),
  ['seed','warm','first','second'].map(name=>({location:loc(name,5),origins:name==='seed'||name==='warm'?[origin]:[]})));
 const begin=source.indexOf('mixed(healthy.'); const end=source.indexOf(');',begin)+1;
 assert.deepEqual(member.prelude,[{kind:'CallExpression',location:{file:'derived.ts',start:position(lineStarts(source),begin),end:position(lineStarts(source),end)}}]);
 assert.deepEqual(member.diagnosticCodes,[]);
 assert.deepEqual(member.demandFailures,[]);
 assert.equal(returned.summary,'any');
 assert.equal(returned.errorType,true);
 assert.deepEqual(returned.diagnosticCodes,[]);
 assert.deepEqual(returned.demandFailures,[]);
 assert.equal(selected.summary,'Mixed<string>');
 assert.equal(selected.errorType,false);
 assert.deepEqual(selected.beforeSummary.observations.unknownSignatureReturn,{errorType:true});
 assert.equal(selected.beforeSummary.counters.unknownSignatureReturns,2);
 assert.deepEqual(selected.diagnosticCodes,[]);
 assert.deepEqual(selected.demandFailures,[]);
 t.diagnostic('Composed generic-alias return is actual errorType; the healthy root still consumes an unknown return during effect-signature acquisition');
});
