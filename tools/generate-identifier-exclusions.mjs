// Run unicode-corpus.mjs and a Rust identifier classification dump first.
// These generated exclusions pin unicode-id-start 1.5 to TypeScript 7's scanner.
import fs from 'node:fs';
const native = fs.readFileSync('.cache/unicode/classification.bin');
const rust = fs.readFileSync('.cache/unicode/rust.bin');
const report = JSON.parse(fs.readFileSync('.cache/unicode/report.json', 'utf8'));
if (native.length !== 0x110000 || rust.length !== native.length) throw new Error('An exhaustive classification is required.');
function ranges(predicate) {
  const result = [];
  for (let cp = 0; cp < native.length; cp++) if (predicate(cp)) {
    const last = result.at(-1);
    if (last && last[1] + 1 === cp) last[1] = cp;
    else result.push([cp, cp]);
  }
  return result;
}
for (let cp = 0; cp < native.length; cp++) {
  if (native[cp] & ~rust[cp]) throw new Error(`Missing Rust identifier support at U+${cp.toString(16)}.`);
}
const excluded = [1, 2].map(bit => ranges(cp => (rust[cp] & bit) && !(native[cp] & bit)));
const constants = excluded.map((list, index) => `const ${index ? 'PART' : 'START'}: &[(u32, u32)] = &[\n${list.map(([lo, hi]) => `    (0x${lo.toString(16)}, 0x${hi.toString(16)}),`).join('\n')}\n];`).join('\n\n');
fs.writeFileSync('src/identifier_exclusions.rs', `// Generated by tools/generate-identifier-exclusions.mjs.\n// Exhaustively checked against ${report.native}, compiler API ${report.api}.\n// Keep these tables paired with unicode-id-start 1.5.0 (Unicode 18).\n\n${constants}\n\npub(crate) fn start(c: char) -> bool { contains(START, c as u32) }\npub(crate) fn part(c: char) -> bool { contains(PART, c as u32) }\nfn contains(ranges: &[(u32, u32)], cp: u32) -> bool {\n    ranges.binary_search_by(|&(lo, hi)| {\n        if cp < lo { std::cmp::Ordering::Greater }\n        else if cp > hi { std::cmp::Ordering::Less }\n        else { std::cmp::Ordering::Equal }\n    }).is_ok()\n}\n`);
fs.writeFileSync('fixtures/identifier-ranges.json', JSON.stringify({ api: report.api, native: report.native,
  start: ranges(cp => native[cp] & 1), part: ranges(cp => native[cp] & 2) }) + '\n');
console.log(JSON.stringify({ startExclusions: excluded[0].length, partExclusions: excluded[1].length }));
