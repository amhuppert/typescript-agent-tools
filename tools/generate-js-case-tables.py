#!/usr/bin/env python3
"""Port TypeScript 7.0.2's pinned Unicode 15.1 JavaScript casing data."""
import ast
import hashlib
import pathlib
import re
import sys
source = pathlib.Path(sys.argv[1]) / 'internal/stringutil/js_case_generated.go'
data = source.read_bytes()
expected = 'Unicode 15.1.0'
text = data.decode()
if expected not in text:
    raise SystemExit('casing source is not pinned Unicode 15.1.0')

def quote(value):
    return '"' + ''.join(chr(c) if 32 <= c < 127 and chr(c) not in '\\"' else f'\\u{{{c:x}}}' for c in map(ord, value)) + '"'

rows = []
for code, fields in re.findall(r'^\s*(0x[0-9A-F]+):\s*\{([^}]+)\},$', text, re.M):
    def field(name):
        match = re.search(name + r':\s*("(?:[^"\\]|\\.)*")', fields)
        return ast.literal_eval(match[1]) if match else ''
    rows.append(f'    ({code}, {quote(field("lower"))}, {quote(field("upper"))}, {quote(field("conditionalLower"))}),')
if not rows:
    raise SystemExit('casing source has no mappings')
output = ['// Generated by tools/generate-js-case-tables.py from TypeScript 7.0.2.',
          '// Unicode 15.1.0; native source SHA-256: ' + hashlib.sha256(data).hexdigest(),
          '// TypeScript source is MIT licensed; see vendor/typescript-7.0.2-lib/LICENSE.',
          '#[rustfmt::skip]',
          'pub(super) const MAPPINGS: &[(u32, &str, &str, &str)] = &[', *rows, '];']
for source_name, target in [('unicodeCasedRanges', 'CASED'), ('unicodeCaseIgnorableRanges', 'CASE_IGNORABLE')]:
    body = text.split('var ' + source_name + ' = ', 1)[1].split('LatinOffset:', 1)[0]
    rows = ['    (' + ', '.join(row) + '),' for row in re.findall(r'\{(0x[0-9A-F]+), (0x[0-9A-F]+), (\d+)\}', body)]
    if not rows:
        raise SystemExit('missing range table: ' + source_name)
    output += ['#[rustfmt::skip]', 'pub(super) const ' + target + ': &[(u32,u32,u32)] = &[', *rows, '];']
pathlib.Path('src/strings/js_case_tables.rs').write_text('\n'.join(output)+'\n')
