// Pin the compiler-facing schema independently of the parser's grammar.
import fs from 'node:fs';
import { spawnSync } from 'node:child_process';
import { loadCompilerApi } from './reference-oracle.mjs';

const ts = loadCompilerApi();
const check = process.argv.includes('--check');
const kinds = Object.fromEntries(Object.entries(ts.SyntaxKind)
  .filter(([name, value]) => typeof value === 'number' && !/^(First|Last)/.test(name) && name !== 'Count'));
const canonical = new Map();
for (const [name, value] of Object.entries(kinds)) {
  if (!canonical.has(value)) canonical.set(value, name);
}
const header = '// Generated by tools/generate-compiler-schema.mjs from TypeScript 6.0.3.\n// Do not edit; this is the TypeScript 7 JSON syntax baseline.\n\n';
const entries = [...canonical.entries()];
const syntax = `${header}#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(u16)]
#[allow(dead_code)] // The complete compiler schema includes kinds we do not emit.
pub(crate) enum SyntaxKind {
${entries.map(([value, name]) => `    ${name} = ${value},`).join('\n')}
}

impl SyntaxKind {
    pub(crate) fn number(self) -> u32 { self as u32 }

    pub(crate) fn name(self) -> &'static str {
        match self {
${entries.map(([, name]) => `            Self::${name} => "${name}",`).join('\n')}
        }
    }
}
`;
const groups = {
  node: ['Let', 'Const', 'Using', 'AwaitUsing', 'NestedNamespace', 'Namespace', 'OptionalChain',
    'GlobalAugmentation', 'DisallowInContext', 'YieldContext', 'DecoratorContext', 'AwaitContext',
    'DisallowConditionalTypesContext', 'PossiblyContainsDynamicImport', 'PossiblyContainsImportMeta',
    'JSDoc', 'Ambient', 'InWithStatement', 'Deprecated', 'IdentifierHasExtendedUnicodeEscape'],
  token: ['ExtendedUnicodeEscape', 'Scientific', 'HexSpecifier', 'BinarySpecifier', 'OctalSpecifier',
    'ContainsSeparator', 'UnicodeEscape', 'ContainsInvalidEscape', 'HexEscape'],
  target: ['Latest'],
  variant: ['Standard', 'JSX'],
  script: ['TS', 'TSX'],
};
const enums = { node: ts.NodeFlags, token: ts.TokenFlags, target: ts.ScriptTarget,
  variant: ts.LanguageVariant, script: ts.ScriptKind };
const constantName = name => name.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase();
const flags = header + Object.entries(groups).map(([group, names]) =>
  `pub(crate) mod ${group} {\n${names.map(name => {
    const value = enums[group][name];
    if (!Number.isInteger(value)) throw new Error(`Missing compiler constant ${group}.${name}`);
    return `    pub(crate) const ${constantName(name)}: u32 = ${value};`;
  }).join('\n')}\n}\n`).join('\n');

function rustfmt(source) {
  const result = spawnSync('rustfmt', ['--edition', '2024'], { input: source, encoding: 'utf8' });
  if (result.error || result.status !== 0) throw new Error(result.error?.message ?? result.stderr);
  return result.stdout;
}
for (const [file, content] of [
  ['src/syntax_kind.rs', rustfmt(syntax)],
  ['src/compiler.rs', rustfmt(flags)],
  ['docs/syntax-kinds.json', JSON.stringify(kinds, null, 2) + '\n'],
]) {
  if (check) {
    if (fs.readFileSync(file, 'utf8') !== content) throw new Error(`${file} needs regeneration`);
  } else fs.writeFileSync(file, content);
}
console.log(`Compiler schema ${check ? 'verified' : 'generated'} from TypeScript ${ts.version}`);
