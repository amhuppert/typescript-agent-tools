// Extract TypeScript 5.6.3's compiler option catalog, the data the
// TypeScript 5.6 dialect's configuration reader converts options with, into
// pinned Rust data (src/project/program/config/catalog_5_6.rs):
// `optionDeclarations` in order, with each option's type, its list element's
// name, type, and `isFilePath`, every enumeration's keys and values and the
// keys its TS6046 message lists, `isCommandLineOnly`, `isFilePath`,
// `allowConfigDirTemplateSubstitution`, and `listPreserveFalsyValues`; and
// the lowered names of the `--build` options, which an unknown option in
// `compilerOptions` that lowers to one reports as TS5093.
// The data records the SHA-256 of the `lib/typescript.js` it came from.
//
//   node tools/ts56-option-catalog.mjs           # rewrite the Rust data
//   node tools/ts56-option-catalog.mjs --check   # exit 1 when it differs
//
// The compiler is the TypeScript 5.6.3 oracle (docs/validation.md).
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { locateTypeScript56 } from './ts56-compiler.mjs';

export const output = fileURLToPath(new URL('../src/project/program/config/catalog_5_6.rs', import.meta.url));

/// The Rust source of the catalog in the 5.6.3 package at `packageDir`.
export function generate(packageDir) {
  const source = path.join(packageDir, 'lib', 'typescript.js');
  const ts = createRequire(import.meta.url)(source);
  if (ts.version !== '5.6.3') throw new Error(`${source} is TypeScript ${ts.version}, not 5.6.3`);
  const sha256 = crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex');
  const enumerations = new Map();
  const elements = [];
  const constant = (prefix, name) => `${prefix}_${name.replace(/[A-Z]/g, c => `_${c}`).toUpperCase()}`;
  const enumeration = (declaration, name) => {
    const id = constant('ENUM', name);
    if (!enumerations.has(id)) {
      const keys = [...declaration.type.keys()];
      const listed = keys.filter(key => !declaration.deprecatedKeys?.has(key)).map(key => `'${key}'`).join(', ');
      const entries = keys.map(key => `(${rust(key)}, ${rust(String(declaration.type.get(key)))})`);
      enumerations.set(id, `pub(super) const ${id}: Enumeration = Enumeration {\n    entries: &[${entries.join(', ')}],\n    listed: ${rust(listed)},\n};`);
    }
    return `Type::Enum(&${id})`;
  };
  const primitive = (declaration, name) => {
    switch (declaration.type) {
      case 'boolean': return 'Type::Boolean';
      case 'number': return 'Type::Number';
      case 'string': return 'Type::String';
      case 'object': return 'Type::Object';
      default:
        if (declaration.type instanceof Map) return enumeration(declaration, name);
        throw new Error(`option ${name}: unexpected type ${declaration.type}`);
    }
  };
  const flag = value => (value ? 'true' : 'false');
  const options = ts.optionDeclarations.map(declaration => {
    let kind;
    if (declaration.type === 'list') {
      const element = declaration.element;
      const id = constant('ELEMENT', declaration.name);
      elements.push(`pub(super) const ${id}: Element = Element {\n    name: ${rust(element.name)},\n    kind: ${primitive(element, declaration.name)},\n    file_path: ${flag(element.isFilePath)},\n};`);
      kind = `Type::List(&${id})`;
    } else if (declaration.type === 'listOrElement') {
      throw new Error(`option ${declaration.name}: listOrElement is not a compiler option kind this catalog knows`);
    } else {
      kind = primitive(declaration, declaration.name);
    }
    return `    Declaration { name: ${rust(declaration.name)}, kind: ${kind}, command_line_only: ${flag(declaration.isCommandLineOnly)}, file_path: ${flag(declaration.isFilePath)}, template: ${flag(declaration.allowConfigDirTemplateSubstitution)}, preserve_falsy: ${flag(declaration.listPreserveFalsyValues)} },`;
  });
  // The keys of `compilerOptionsAlternateMode`'s name map, which
  // `createOptionNameMap` lowers.
  const buildKeys = [...new Set(ts.buildOpts.map(declaration => declaration.name.toLowerCase()))];
  return [
    '// Generated by tools/ts56-option-catalog.mjs from TypeScript 5.6.3; do not edit.',
    '// tools/ts56-option-catalog.test.mjs re-extracts it from the pinned compiler.',
    '// TypeScript is Apache-2.0 licensed.',
    '',
    'use super::catalog::{Declaration, Element, Enumeration, Type};',
    '',
    'pub(super) const VERSION: &str = "5.6.3";',
    '',
    '/// The SHA-256 of the `lib/typescript.js` this catalog was extracted from.',
    '#[cfg_attr(not(test), expect(dead_code, reason = "provenance, which tests check"))]',
    'pub(super) const SOURCE_SHA256: &str =',
    `    ${rust(sha256)};`,
    '',
    '/// `optionDeclarations`, in order; `help` is declared twice.',
    '#[rustfmt::skip]',
    'pub(super) const OPTIONS: &[Declaration] = &[',
    ...options,
    '];',
    '',
    '/// `buildOpts` names, lowered as `createOptionNameMap` keys them: an',
    '/// unknown option that lowers to one is TS5093.',
    '#[rustfmt::skip]',
    `pub(super) const BUILD_KEYS: &[&str] = &[${buildKeys.map(rust).join(', ')}];`,
    '',
    ...[...elements, ...enumerations.values()].flatMap(item => ['#[rustfmt::skip]', item, '']),
  ].join('\n').replace(/\n+$/, '\n');
}

/// A Rust string literal for `text`, escaping everything outside printable
/// ASCII so the data reads the same in any editor.
export function rust(text) {
  let literal = '"';
  for (const character of text) {
    const code = character.codePointAt(0);
    if (character === '"' || character === '\\') literal += `\\${character}`;
    else if (code >= 0x20 && code < 0x7f) literal += character;
    else literal += `\\u{${code.toString(16)}}`;
  }
  return `${literal}"`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  try {
    const generated = generate(locateTypeScript56().packageDir);
    if (check) {
      const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
      if (current !== generated) {
        console.error(`${path.relative(process.cwd(), output)} differs from the pinned compiler's catalog; run node tools/ts56-option-catalog.mjs`);
        process.exit(1);
      }
    } else {
      fs.writeFileSync(output, generated);
    }
  } catch (error) {
    console.error(`ts56-option-catalog: ${error.message}`);
    process.exit(2);
  }
}
