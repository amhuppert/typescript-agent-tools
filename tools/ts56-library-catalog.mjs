// Extract TypeScript 5.6.3's standard library catalog, the data the
// TypeScript 5.6 dialect selects library files with, into pinned Rust data
// (src/project/program/libraries/catalog_5_6.rs): `libs`, each library name
// in `libEntries` order with a name declared twice at both places, which
// `getDefaultLibFilePriority` orders files by and an unknown
// `/// <reference lib>` takes its suggestion from; `libMap`, the file each
// name selects, the last one declared for a repeated name; and
// `getDefaultLibFileName` for each `target` key and for any other target.
// The data records the SHA-256 of the `lib/typescript.js` it came from. The
// declarations themselves are not extracted: the dialect reads them from the
// installed compiler's own `lib/` directory.
//
//   node tools/ts56-library-catalog.mjs           # rewrite the Rust data
//   node tools/ts56-library-catalog.mjs --check   # exit 1 when it differs
//
// The compiler is the TypeScript 5.6.3 oracle (docs/validation.md).
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { locateTypeScript56 } from './ts56-compiler.mjs';
import { rust } from './ts56-option-catalog.mjs';

export const output = fileURLToPath(new URL('../src/project/program/libraries/catalog_5_6.rs', import.meta.url));

/// The library catalog of the 5.6.3 compiler module `ts`.
export function catalog(ts) {
  const defaults = [...ts.targetOptionDeclaration.type].map(([key, target]) => [key, ts.getDefaultLibFileName({ target })]);
  return {
    libs: [...ts.libs],
    libMap: [...ts.libMap],
    defaults,
    // `getEmitScriptTarget` of options without `target` or `module` is ES5,
    // whose default stands for every target the table lacks.
    otherDefault: ts.getDefaultLibFileName({}),
  };
}

/// The Rust source of the catalog in the 5.6.3 package at `packageDir`.
export function generate(packageDir) {
  const source = path.join(packageDir, 'lib', 'typescript.js');
  const ts = createRequire(import.meta.url)(source);
  if (ts.version !== '5.6.3') throw new Error(`${source} is TypeScript ${ts.version}, not 5.6.3`);
  const sha256 = crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex');
  const { libs, libMap, defaults, otherDefault } = catalog(ts);
  const pairs = entries => entries.map(([key, file]) => `    (${rust(key)}, ${rust(file)}),`);
  return [
    '// Generated by tools/ts56-library-catalog.mjs from TypeScript 5.6.3; do not edit.',
    '// tools/ts56-library-catalog.test.mjs re-extracts it from the pinned compiler.',
    '// TypeScript is Apache-2.0 licensed.',
    '',
    '#[cfg_attr(not(test), expect(dead_code, reason = "provenance, which tests check"))]',
    'pub(super) const VERSION: &str = "5.6.3";',
    '',
    '/// The SHA-256 of the `lib/typescript.js` this catalog was extracted from.',
    '#[cfg_attr(not(test), expect(dead_code, reason = "provenance, which tests check"))]',
    'pub(super) const SOURCE_SHA256: &str =',
    `    ${rust(sha256)};`,
    '',
    '/// `libs`: each library name in `libEntries` order, a name declared twice',
    '/// at both places.',
    '#[rustfmt::skip]',
    'pub(super) const LIBS: &[&str] = &[',
    ...libs.map(name => `    ${rust(name)},`),
    '];',
    '',
    '/// `libMap`: each library name, in the order names first appear, and the',
    '/// last file declared for it.',
    '#[rustfmt::skip]',
    'pub(super) const LIB_MAP: &[(&str, &str)] = &[',
    ...pairs(libMap),
    '];',
    '',
    '/// `getDefaultLibFileName` for each key of `target`, in declaration order.',
    '#[rustfmt::skip]',
    'pub(super) const DEFAULT_LIBRARIES: &[(&str, &str)] = &[',
    ...pairs(defaults),
    '];',
    '',
    '/// `getDefaultLibFileName` for a target `target` has no key for.',
    `pub(super) const OTHER_DEFAULT_LIBRARY: &str = ${rust(otherDefault)};`,
  ].join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  try {
    const generated = generate(locateTypeScript56().packageDir);
    if (check) {
      const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
      if (current !== generated) {
        console.error(`${path.relative(process.cwd(), output)} differs from the pinned compiler's library catalog; run node tools/ts56-library-catalog.mjs`);
        process.exit(1);
      }
    } else {
      fs.mkdirSync(path.dirname(output), { recursive: true });
      fs.writeFileSync(output, generated);
    }
  } catch (error) {
    console.error(`ts56-library-catalog: ${error.message}`);
    process.exit(2);
  }
}
