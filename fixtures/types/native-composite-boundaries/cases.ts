export {};
declare function choosePredicate(value: (input: unknown) => input is string | number): "chosen";
declare function choosePredicate(value: unknown): "fallback";
declare const joinedPredicate: ((input: unknown) => input is string) | ((input: unknown) => input is number);
declare const falsePredicate: ((input: unknown) => input is string) | ((input: unknown) => false);
declare const booleanPredicate: ((input: unknown) => input is string) | ((input: unknown) => boolean);
declare const assertionPredicate: ((input: unknown) => asserts input is string) | ((input: unknown) => asserts input is number);
declare function chooseTwo(value: (left: unknown, right: unknown) => left is string | number): "chosen";
declare function chooseTwo(value: unknown): "fallback";
declare const mismatchPredicate: ((left: unknown, right: unknown) => left is string) | ((left: unknown, right: unknown) => right is number);
declare function chooseMixed(value: new (value: string) => { a: string; b: number }): "chosen";
declare function chooseMixed(value: unknown): "fallback";
declare const mixedConstructor: (new (...args: any[]) => { a: string }) & (new (value: string) => { b: number });
declare const allMixedConstructor: (new (...args: any[]) => { a: string }) & (new (...args: any[]) => { b: number });
declare const readonlyMixedConstructor: (new (...args: readonly any[]) => { a: string }) & (new (value: string) => { b: number });
declare const mutableArrays: string[] | number[];
declare const readonlyArrays: readonly string[] | readonly number[];
declare const mixedArrays: string[] | readonly number[];
declare const test: (value: string | number) => boolean;
export const /*#predicate*/predicateResult = choosePredicate(joinedPredicate);
export const /*#falsePredicate*/falsePredicateResult = choosePredicate(falsePredicate);
export const /*#booleanPredicate*/booleanPredicateResult = choosePredicate(booleanPredicate);
export const /*#assertionPredicate*/assertionPredicateResult = choosePredicate(assertionPredicate);
export const /*#mismatchPredicate*/mismatchPredicateResult = chooseTwo(mismatchPredicate);
export const /*#mixin*/mixinResult = chooseMixed(mixedConstructor);
export const /*#allMixins*/allMixinsResult = chooseMixed(allMixedConstructor);
export const /*#readonlyMixin*/readonlyMixinResult = chooseMixed(readonlyMixedConstructor);
export const /*#mutableArrays*/mutableArraysResult = mutableArrays.filter(test);
export const /*#readonlyArrays*/readonlyArraysResult = readonlyArrays.filter(test);
export const /*#mixedArrays*/mixedArraysResult = mixedArrays.filter(test);
